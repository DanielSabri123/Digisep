public class MateriaClickEscolar {
    private String folioOrdenamiento;
    private String claveSep;
    private String nombreMat;
    private String creditosMateria;
    private String idTipoAsignatura;

    public String getFolioOrdenamiento() {
        return folioOrdenamiento;
    }

    public void setFolioOrdenamiento(String folioOrdenamiento) {
        this.folioOrdenamiento = folioOrdenamiento;
    }

    public String getClaveSep() {
        return claveSep;
    }

    public void setClaveSep(String claveSep) {
        this.claveSep = claveSep;
    }

    public String getNombreMat() {
        return nombreMat;
    }

    public void setNombreMat(String nombreMat) {
        this.nombreMat = nombreMat;
    }

    public String getCreditoMateria() {
        return creditosMateria;
    }

    public void setCreditoMateria(String creditoMateria) {
        this.creditosMateria = creditoMateria;
    }

    public String getIdTipoAsignatura() {
        return idTipoAsignatura;
    }

    public void setIdTipoAsignatura(String idTipoAsignatura) {
        this.idTipoAsignatura = idTipoAsignatura;
    }
    
    
}
